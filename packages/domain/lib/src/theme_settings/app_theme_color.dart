/// アプリ全体で使うThemeColor（ベースとなるSeed Color）の区分。
enum AppThemeColor {
  /// アプリ固有のブランドカラーをSeed Colorとして使う。
  app,

  /// OSのDynamic Color（壁紙由来の配色）をSeed Colorとして使う。
  dynamic,

  /// 青系をSeed Colorとして使う。
  blue,

  /// 紫系をSeed Colorとして使う。
  purple,

  /// ピンク系をSeed Colorとして使う。
  pink,

  /// 赤系をSeed Colorとして使う。
  red,

  /// オレンジ系をSeed Colorとして使う。
  orange,

  /// 黄系をSeed Colorとして使う。
  yellow,

  /// 緑系をSeed Colorとして使う。
  green,
}
